-- HotelGroup | US-03-07 | Wspolne kategorie kosztowe i polityka walutowa
-- PostgreSQL. Rozszerzenie istniejacych schematow core i mart.
-- Uwaga: skrypt tworzy struktury. NIE oznacza akceptacji kategorii przez kontrolera.
-- Uruchom po skryptach utworzenia schematow staging/core/mart.

BEGIN;

CREATE SCHEMA IF NOT EXISTS core;
CREATE SCHEMA IF NOT EXISTS mart;

-- Jeden kod kosztowy w calej sieci. Wszystkie wpisy poczatkowo wymagaja akceptacji.
CREATE TABLE IF NOT EXISTS core.cost_category (
    cost_category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code VARCHAR(50) NOT NULL UNIQUE,
    category_name VARCHAR(150) NOT NULL,
    category_group VARCHAR(80) NOT NULL,
    business_definition TEXT NOT NULL,
    gop_treatment VARCHAR(20) NOT NULL DEFAULT 'TO_REVIEW'
        CHECK (gop_treatment IN ('INCLUDED', 'EXCLUDED', 'TO_REVIEW')),
    approval_status VARCHAR(12) NOT NULL DEFAULT 'DRAFT'
        CHECK (approval_status IN ('DRAFT', 'APPROVED', 'REJECTED')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_cost_category_code
        CHECK (category_code ~ '^[A-Z][A-Z0-9_]*$')
);

-- Jawne mapowanie lokalnych kodow. Nie scala sie kodow na podstawie podobienstwa nazw.
-- Przedzial waznosci: [valid_from, valid_to), NULL = bez terminu koncowego.
CREATE TABLE IF NOT EXISTS core.hotel_cost_category_mapping (
    mapping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_system VARCHAR(50) NOT NULL DEFAULT 'FINANCE_CSV',
    hotel_id VARCHAR(50) NOT NULL,
    local_cost_code VARCHAR(100) NOT NULL,
    cost_category_id BIGINT NOT NULL REFERENCES core.cost_category(cost_category_id),
    valid_from DATE NOT NULL,
    valid_to DATE,
    decision_status VARCHAR(12) NOT NULL DEFAULT 'DRAFT'
        CHECK (decision_status IN ('DRAFT', 'APPROVED', 'REJECTED')),
    approved_by VARCHAR(120),
    approval_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_mapping_local_code CHECK (length(btrim(local_cost_code)) > 0),
    CONSTRAINT ck_mapping_period CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT ck_mapping_approved_by CHECK (decision_status <> 'APPROVED' OR approved_by IS NOT NULL),
    CONSTRAINT uq_mapping_start UNIQUE (source_system, hotel_id, local_cost_code, valid_from)
);

CREATE INDEX IF NOT EXISTS ix_cost_mapping_lookup
ON core.hotel_cost_category_mapping (hotel_id, source_system, local_cost_code, valid_from, valid_to)
WHERE decision_status = 'APPROVED';

-- Zasady walut dla pojedynczego strumienia z konkretnego hotelu.
-- Staging.fin_budgets_costs obecnie nie posiada pola waluty: polityke trzeba potwierdzic
-- przed interpretacja kwot; jesli dane sa wielowalutowe w jednym strumieniu,
-- konieczne jest rozszerzenie kontraktu zrodlowego o currency_code dla kazdego rekordu.
CREATE TABLE IF NOT EXISTS core.finance_currency_policy (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_system VARCHAR(50) NOT NULL DEFAULT 'FINANCE_CSV',
    hotel_id VARCHAR(50) NOT NULL,
    source_currency CHAR(3) NOT NULL,
    reporting_currency CHAR(3) NOT NULL DEFAULT 'PLN',
    valid_from DATE NOT NULL,
    valid_to DATE,
    approval_status VARCHAR(12) NOT NULL DEFAULT 'DRAFT'
        CHECK (approval_status IN ('DRAFT', 'APPROVED', 'REJECTED')),
    approved_by VARCHAR(120),
    conversion_rule TEXT NOT NULL,
    CONSTRAINT ck_finance_currency_codes CHECK (
        source_currency ~ '^[A-Z]{3}$' AND reporting_currency ~ '^[A-Z]{3}$'
    ),
    CONSTRAINT ck_finance_policy_period CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT ck_finance_policy_approver CHECK (approval_status <> 'APPROVED' OR approved_by IS NOT NULL),
    CONSTRAINT uq_finance_policy_start UNIQUE (source_system, hotel_id, valid_from)
);

-- Wymiar raportowy z osobnym kluczem zastępczym. Zasilanie z zatwierdzonych
-- kategorii w core jest osobnym etapem procesu transformacji (nie przez ten DDL).
CREATE TABLE IF NOT EXISTS mart.dim_cost_category (
    cost_category_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cost_category_bk VARCHAR(50) NOT NULL UNIQUE,
    category_name VARCHAR(150) NOT NULL,
    category_group VARCHAR(80) NOT NULL,
    business_definition TEXT NOT NULL,
    gop_treatment VARCHAR(20) NOT NULL
        CHECK (gop_treatment IN ('INCLUDED', 'EXCLUDED', 'TO_REVIEW')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

COMMIT;
