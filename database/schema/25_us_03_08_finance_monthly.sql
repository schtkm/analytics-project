-- HotelGroup | US-03-08 | Miesieczny model finansowy
-- Ziarno: hotel x miesiac x kategoria x scenariusz
-- Skrypt tworzy strukture, bez zasilania danymi.

BEGIN;

CREATE TABLE IF NOT EXISTS mart.fct_finance_monthly (
    finance_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    hotel_sk INTEGER NOT NULL
        REFERENCES mart.dim_hotel(hotel_sk),

    month_date_sk INTEGER NOT NULL
        REFERENCES mart.dim_date(date_sk),

    cost_category_sk BIGINT NOT NULL
        REFERENCES mart.dim_cost_category(cost_category_sk),

    scenario VARCHAR(10) NOT NULL
        CHECK (scenario IN ('ACTUAL', 'BUDGET')),

    amount NUMERIC(18,2) NOT NULL
        CHECK (amount >= 0),

    currency_code CHAR(3) NOT NULL DEFAULT 'PLN'
        CHECK (currency_code ~ '^[A-Z]{3}$'),

    CONSTRAINT uq_finance_monthly_grain
        UNIQUE (
            hotel_sk,
            month_date_sk,
            cost_category_sk,
            scenario
        )
);

CREATE INDEX IF NOT EXISTS ix_finance_monthly_hotel_month
    ON mart.fct_finance_monthly (hotel_sk, month_date_sk);

CREATE INDEX IF NOT EXISTS ix_finance_monthly_category
    ON mart.fct_finance_monthly (cost_category_sk);

COMMIT;